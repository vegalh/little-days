// The English text is its own key: translate("zh", "Explore") looks it up in
// ZH, and English (or any text without an entry) comes back unchanged. {name} marks a
// value filled in by the caller. tests/i18n.test.js checks that every English text the
// page uses has a Chinese entry, with the same {placeholders}.

const LANGS = ["en", "zh"];

function translate(lang, text, vars = {}) {
  const template = lang === "zh" && ZH[text] !== undefined ? ZH[text] : text;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

// "zh" for any Chinese browser language (zh-CN, zh-TW, zh-HK…), otherwise "en".
function deviceLanguage(languages) {
  return (languages || []).some((language) => /^zh\b/i.test(language)) ? "zh" : "en";
}

